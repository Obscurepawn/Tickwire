#!/usr/bin/env python3
"""Independent, small RFC 8949 encoder for schema-2 command-bound inputs.

Run with --check to compare generated bytes with the immutable fixture.
This script never calls the Rust crate.
"""
import argparse
import hashlib
import json
from pathlib import Path


def argument(major, value):
    if value < 24:
        return bytes([major << 5 | value])
    for width, additional in ((1, 24), (2, 25), (4, 26), (8, 27)):
        if value < (1 << (8 * width)):
            return bytes([major << 5 | additional]) + value.to_bytes(width, "big")
    raise ValueError("argument exceeds u64")


def cbor(value):
    if isinstance(value, int):
        magnitude = value if value >= 0 else -1 - value
        if magnitude <= (1 << 64) - 1:
            return argument(0 if value >= 0 else 1, magnitude)
        raw = magnitude.to_bytes((magnitude.bit_length() + 7) // 8, "big")
        return bytes([0xC2 if value >= 0 else 0xC3]) + cbor(raw)
    if isinstance(value, bytes):
        return argument(2, len(value)) + value
    if isinstance(value, str):
        raw = value.encode("utf-8")
        return argument(3, len(raw)) + raw
    if isinstance(value, list):
        return argument(4, len(value)) + b"".join(map(cbor, value))
    if isinstance(value, dict):
        pairs = sorted((cbor(k), cbor(v)) for k, v in value.items())
        return argument(5, len(pairs)) + b"".join(k + v for k, v in pairs)
    raise TypeError(value)


def digest(value):
    return hashlib.sha256(cbor(value)).digest()


def fixtures():
    # These integer bytes are independently transcribed from RFC 8949 Appendix A.
    rfc = {
        0: "00", 23: "17", 24: "1818", 255: "18ff", 256: "190100",
        1000000: "1a000f4240", 1000000000000: "1b000000e8d4a51000",
        -1: "20", -24: "37", -25: "3818", -1000: "3903e7",
        18446744073709551615: "1bffffffffffffffff",
        18446744073709551616: "c249010000000000000000",
        -18446744073709551616: "3bffffffffffffffff",
        -18446744073709551617: "c349010000000000000000",
    }
    for value, wire in rfc.items():
        assert cbor(value).hex() == wire
    amounts = list(rfc) + [(1 << 127) - 1, -(1 << 127)]
    domain, epoch = bytes(range(16)), bytes(range(16, 32))
    common = {0: 1, 1: 2, 2: 1, 3: 3, 4: 9, 5: 7}
    events = [
        ("prepared", 1, common | {6: 4, 7: 10, 8: 2, 9: 8, 10: 9, 11: 10, 12: 11, 13: 1, 14: bytes([9] * 32)}),
        ("fill", 2, common | {6: 4, 7: 2, 8: 20}),
        ("fee", 3, common | {6: 5, 7: -1}),
        ("terminal", 4, common | {6: 2, 7: 2}),
        ("aborted", 5, common),
        ("late_fill", 2, common | {6: 4, 7: 2, 8: 20}),
    ]
    h = digest(["tickwire.logical-genesis", 2, domain, epoch])
    result = {"genesis": h.hex(), "events": [], "integers": []}
    for seq, (name, kind, payload) in enumerate(events, 1):
        writer_epoch = 8 if name == "late_fill" else 7
        record = {0: 2, 1: domain, 2: epoch, 3: seq, 4: writer_epoch, 5: kind, 6: payload}
        business = digest(["tickwire.business-event", 2, domain, kind, payload])
        p = digest(["tickwire.logical-payload", 2, writer_epoch, business])
        h = hashlib.sha256(h + cbor([
            "tickwire.logical-record", 2, domain, epoch, seq, kind, p
        ])).digest()
        result["events"].append({
            "name": name, "wire": cbor(record).hex(),
            "business_digest": business.hex(), "logical_payload_hash": p.hex(),
            "logical_hash": h.hex(),
        })
    maximum = (1 << 64) - 1
    payload = {
        0: (1 << 32) - 1, 1: maximum, 2: 2, 3: maximum, 4: maximum,
        5: maximum, 6: maximum, 7: (1 << 127) - 1, 8: -(1 << 127), 9: maximum,
        10: maximum, 11: maximum, 12: maximum, 13: 2, 14: bytes([255] * 32),
    }
    wire = cbor({0: 2, 1: domain, 2: epoch, 3: maximum, 4: maximum, 5: 1, 6: payload})
    assert len(wire) == 236
    business = digest(["tickwire.business-event", 2, domain, 1, payload])
    result["maximum"] = {
        "wire": wire.hex(),
        "business_digest": business.hex(),
        "logical_payload_hash": digest(["tickwire.logical-payload", 2, maximum, business]).hex(),
    }
    result["integers"] = [{"value": str(v), "wire": cbor(v).hex()} for v in amounts]
    return json.dumps(result, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[3] / "crates/tickwire-journal-codec/tests/golden-v2.json"
    expected = fixtures()
    if args.check:
        assert target.read_text() == expected, "golden fixture drift"
        print("PASS: independent RFC encoder, 6 records / 5 event types, 236-byte maximum, 17 integer vectors")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected)


if __name__ == "__main__":
    main()
