#!/usr/bin/env python3
"""Generate fixed offsets only; fail if the pinned XML source has changed."""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
lock = json.loads((ROOT / 'schema/source.json').read_text())
xml = (ROOT / 'schema/stream_1_0.xml').read_bytes()
assert hashlib.sha256(xml).hexdigest() == lock['sha256']
schema = ET.fromstring(xml)
assert int(schema.attrib['id']) == lock['schema_id'] == 1
assert int(schema.attrib['version']) == lock['version'] == 0
assert schema.attrib['byteOrder'] == 'littleEndian'
sizes = {'uint8': 1, 'int8': 1, 'uint16': 2, 'uint32': 4, 'int64': 8}
types = schema.find('types')
for child in types:
    if child.tag == 'type':
        sizes[child.attrib['name']] = sizes[child.attrib['primitiveType']]
    elif child.tag == 'enum':
        sizes[child.attrib['name']] = sizes[child.attrib['encodingType']]

def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()

def fields(parent):
    offset = 0
    result = []
    for f in parent.findall('field'):
        if f.get('presence') == 'constant':
            continue
        result.append(f"pub const {snake(f.get('name')).upper()}: usize = {offset};")
        offset += sizes[f.get('type')]
    result.append(f'pub const BLOCK_LENGTH: usize = {offset};')
    return result

out = ['// Generated by tools/generate.py from the pinned official XML.',
       f'pub const SOURCE_SHA256: &str = "{lock["sha256"]}";',
       'pub const SCHEMA_ID: u16 = 1;', 'pub const VERSION: u16 = 0;',
       'pub const MESSAGE_HEADER_BYTES: usize = 8;']
messages = schema.findall('{http://fixprotocol.io/2016/sbe}message')
assert {int(m.get('id')) for m in messages} == {10000, 10001, 10002, 10003}
for m in messages:
    out += [f'pub mod {snake(m.get("name"))} {{',
            f'pub const TEMPLATE_ID: u16 = {m.get("id")};', *fields(m)]
    for g in m.findall('group'):
        dimension = g.get('dimensionType', 'groupSizeEncoding')
        assert dimension in ('groupSizeEncoding', 'groupSize16Encoding')
        out += [f'pub mod {g.get("name")} {{', *fields(g),
                f'pub const HEADER_BYTES: usize = {6 if dimension == "groupSizeEncoding" else 4};', '}']
    out += ['}']
target = ROOT / 'src/schema.rs'
target.write_text('\n'.join(out) + '\n')
subprocess.run([str(Path.home()/'.cargo/bin/rustfmt'), '--edition', '2024', str(target)], check=True)
