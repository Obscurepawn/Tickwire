#!/usr/bin/env python3
"""Generate explicit Rust wire types or golden tests; runtime has no schema interpreter."""
import json
import hashlib
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
CRATE = pathlib.Path(__file__).resolve().parents[1]
contract = json.loads((ROOT / "specs/contracts/ipc-wire-v1.json").read_text())
vectors = json.loads((ROOT / "specs/contracts/ipc-vectors-v1.json").read_text())["vectors"]
layouts = {layout["name"]: layout for layout in contract["layouts"]}
scalars = {"u8", "i8", "u16", "i16", "u32", "i32", "u64", "i64", "atomic_u64"}

def write_rust(relative, text):
    path = CRATE / relative
    path.write_text(text)
    rustfmt = shutil.which("rustfmt") or str(pathlib.Path.home()/".cargo/bin/rustfmt")
    subprocess.run([rustfmt, "--edition", "2024", str(path)], check=True)

def pattern(values):
    values=sorted(set(values))
    if values==list(range(values[0],values[-1]+1)) and len(values)>2:
        return f"{values[0]}..={values[-1]}"
    return "|".join(map(str,values))

def typ(field):
    raw = field["type"]
    base = "u64" if raw == "atomic_u64" else "u8" if raw == "bytes" else raw
    count = field.get("count", 1)
    return f"[{base}; {count}]" if count != 1 or raw == "bytes" else base

def init(layout, values):
    fields = []
    for field in layouts[layout]["fields"]:
        name, raw = field["name"], field["type"]
        if field.get("reserved") or name not in values:
            continue
        value = values[name]
        count = field.get("count", 1)
        if raw == "bytes":
            data = bytes.fromhex(value).ljust(field["size"], b"\0")
            expr = "[" + ",".join(str(x) for x in data) + "]"
        elif raw in scalars:
            expr = repr(value).lower()
        elif count == 1:
            expr = init(raw, value)
        else:
            expr = "[" + ",".join(init(raw, item) for item in value)
            expr += ("," if value else "") + ",".join(f"{raw}::default()" for _ in range(count-len(value))) + "]"
        fields.append(f"{name}: {expr}")
    tail = ", ..Default::default()" if len(fields) < sum(not f.get("reserved",False) for f in layouts[layout]["fields"]) else ""
    return layout + " { " + ", ".join(fields) + tail + " }"

def tests():
    out = ["// Generated by tools/generate.py tests. Golden bytes are independent fixture expectations.",
           "use tickwire_ipc::*;", "fn hex(s: &str) -> Vec<u8> { (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i+2],16).unwrap()).collect() }"]
    for vector in vectors:
        name, layout = vector["name"], vector["layout"]
        out.append(f"fn bytes_{name}() -> Vec<u8> {{ hex(\"{vector['hex']}\") }}")
        out.append(f"#[test] fn golden_{name}() {{ let expected = bytes_{name}();")
        if layout in layouts:
            out.append(f"let value = {init(layout, vector['values'])};")
            out.append("let mut encoded = vec![0xCC; expected.len()]; value.encode(&mut encoded).unwrap(); assert_eq!(encoded, expected);")
            out.append(f"assert_eq!({layout}::decode(&expected).unwrap(), value);")
        elif layout == "ControlFrame":
            out.append("let mut encoded = Vec::new();")
            for part in vector["parts"]:
                out.append(f"encoded.extend_from_slice(&bytes_{part}());")
            out.append("assert_eq!(encoded, expected); ControlFrame::decode(&expected).unwrap();")
        else:
            out.append("let mut encoded = vec![0; expected.len()];")
            for segment in vector["segments"]:
                end=f"{segment['offset']}+part.len()" if segment["offset"] else "part.len()"
                out.append(f"let part = bytes_{segment['vector']}(); encoded[{segment['offset']}..{end}].copy_from_slice(&part);")
            out.append("assert_eq!(encoded, expected);")
        out.append("}")
    write_rust("tests/vectors.rs","\n".join(out)+"\n")
    out = ["// Generated fixed-layout boundary tests.", "use tickwire_ipc::*;"]
    for layout in layouts.values():
        name,size = layout["name"],layout["size"]
        out.append(f"#[test] fn layout_{name.lower()}() {{let value={name}::default(); let mut raw=vec![0xCC;{size}]; value.encode(&mut raw).unwrap(); assert_eq!({name}::decode(&raw).unwrap(),value);")
        out.append(f"for length in [0,{size-1},{size+1}] {{assert_eq!({name}::decode(&vec![0;length]),Err(Error::Bounds)); assert_eq!(value.encode(&mut vec![0;length]),Err(Error::Bounds));}}")
        for f in layout["fields"]:
            if f.get("reserved"):
                out.append(f"for i in {f['offset']}..{f['offset']+f['size']} {{raw[i]=1; assert_eq!({name}::decode(&raw),Err(Error::ReservedNonzero));raw[i]=0;}}")
        out.append("}")
    write_rust("tests/layouts.rs","\n".join(out)+"\n")

def production():
    out = ["// Generated by tools/generate.py wire. Do not hand-edit offsets.",
           "use crate::{Error, Result, Wire, zero};"]
    digest=hashlib.sha256((ROOT / "specs/contracts/ipc-wire-v1.json").read_bytes()).digest()
    out.append(f"pub const WIRE_LAYOUT_COUNT: usize = {len(layouts)};")
    out.append("pub const WIRE_CONTRACT_SHA256: [u8;32] = ["+",".join(map(str,digest))+"];")
    for layout in layouts.values():
        name, size = layout["name"], layout["size"]
        fields = [field for field in layout["fields"] if not field.get("reserved")]
        derive_default=all(f.get("count",1)<=32 for f in fields)
        derive=", Default" if derive_default else ""
        out.append(f"#[derive(Debug, Clone, PartialEq, Eq{derive})] pub struct {name} {{")
        out.extend(f"pub {field['name']}: {typ(field)}," for field in fields)
        out.append("}")
        if not derive_default:
            out.append(f"impl Default for {name} {{ fn default() -> Self {{ Self {{")
            for field in fields:
                raw, count = field["type"], field.get("count",1)
                val = "0" if raw in scalars or raw == "bytes" else f"{raw}::default()"
                if count != 1 or raw == "bytes": val = f"core::array::from_fn(|_| {val})"
                out.append(f"{field['name']}: {val},")
            out.append("} } }")
        out.append(f"impl Wire for {name} {{ const SIZE: usize = {size};")
        out.append("fn decode(raw: &[u8]) -> Result<Self> { if raw.len()!=Self::SIZE { return Err(Error::Bounds); }")
        for field in layout["fields"]:
            n, raw, offset, length, count = field["name"], field["type"], field["offset"], field["size"], field.get("count",1)
            if field.get("reserved"):
                out.append(f"zero(&raw[{offset}..{offset+length}])?;")
                continue
            target = f"raw[{offset}..{offset+length}]"
            if raw == "bytes": value = f"{target}.try_into().map_err(|_| Error::Bounds)?"
            elif raw in scalars:
                t = "u64" if raw == "atomic_u64" else raw
                value = f"{t}::from_le_bytes({target}.try_into().map_err(|_| Error::Bounds)?)"
                assert count == 1
            elif count == 1: value = f"{raw}::decode(&{target})?"
            else:
                unit = layouts[raw]["size"]
                out.append(f"let mut {n}: [{raw}; {count}] = core::array::from_fn(|_| {raw}::default()); for (i,value) in {n}.iter_mut().enumerate() {{ *value={raw}::decode(&raw[{offset}+i*{unit}..{offset}+(i+1)*{unit}])?; }}")
                continue
            out.append(f"let {n} = {value};")
        out.append("Ok(Self { "+",".join(field["name"] for field in fields)+" }) }")
        out.append("fn encode(&self, out: &mut [u8]) -> Result<()> { if out.len()!=Self::SIZE { return Err(Error::Bounds); } out.fill(0);")
        for field in fields:
            n, raw, offset, length, count = field["name"], field["type"], field["offset"], field["size"], field.get("count",1)
            target = f"out[{offset}..{offset+length}]"
            if raw == "bytes": out.append(f"{target}.copy_from_slice(&self.{n});")
            elif raw in scalars: out.append(f"{target}.copy_from_slice(&self.{n}.to_le_bytes());")
            elif count == 1: out.append(f"self.{n}.encode(&mut {target})?;")
            else:
                unit = layouts[raw]["size"]
                out.append(f"for (i,value) in self.{n}.iter().enumerate() {{ value.encode(&mut out[{offset}+i*{unit}..{offset}+(i+1)*{unit}])?; }}")
        out.append("Ok(()) } }")
    out.append("pub(crate) fn validate_fields(id: u16, raw: &[u8]) -> Result<()> { match id {")
    for msg in contract["messages"]:
        constraint = contract["message_constraints"][msg["name"]]
        layout = layouts[msg["body_layout"]]
        out.append(f"{msg['id']} => {{ if raw.len()!={layout['size']} {{return Err(Error::Bounds);}}")
        for field in layout["fields"]:
            n, off, size = field["name"], field["offset"], field["size"]
            if n not in constraint["allowed_fields"]:
                out.append(f"zero(&raw[{off}..{off+size}])?;")
            elif field["type"] in scalars:
                enum = contract["enums"].get(n)
                bits = contract["bitsets"].get(n)
                if enum:
                    allowed = pattern(set(enum.values())|{0})
                    out.append(f"if !matches!(crate::uint(&raw[{off}..{off+size}]), {allowed}) {{ return Err(Error::InvalidEnum); }}")
                if bits:
                    mask = sum(1 << v for v in bits.values())
                    out.append(f"if crate::uint(&raw[{off}..{off+size}]) & !{mask}u64 != 0 {{return Err(Error::Malformed);}}")
        for name in ["command_kind", "report_kind"]:
            if name in constraint:
                field = next(f for f in layout["fields"] if f["name"] == name)
                off, size = field["offset"], field["size"]
                out.append(f"if crate::uint(&raw[{off}..{off+size}])!={constraint[name]} {{return Err(Error::Malformed);}}")
        if "value_validity_allowed_mask" in constraint:
            field = next(f for f in layout["fields"] if f["name"] == "value_validity")
            off = field["offset"]
            allowed, required = constraint["value_validity_allowed_mask"], constraint["value_validity_required_mask"]
            condition=f"mask & !{allowed}u64 != 0" if allowed else "mask != 0"
            if required:
                condition+=f" || mask & {required} != {required}"
            out.append(f"let mask=crate::uint(&raw[{off}..{off+8}]); if {condition} {{return Err(Error::Malformed);}}")
            for bit, n in enumerate(contract["report_value_fields"]):
                field = next(f for f in layout["fields"] if f["name"] == n)
                off = field["offset"]
                out.append(f"if mask & (1 << {bit}) == 0 && raw[{off}..{off+8}].iter().any(|&b|b!=0) {{return Err(Error::Malformed);}}")
        out.append("Ok(()) },")
    out.append("_ => Err(Error::UnknownMessage) } }")
    out.append("pub(crate) fn validate_control_body(op: u16, flags: u32, raw: &[u8]) -> Result<()> { match op {")
    for op in contract["control_opcodes"]:
        flags = "|".join(map(str,op["allowed_flags"]))
        out.append(f"{op['id']} => {{ if !matches!(flags, {flags}) {{return Err(Error::Malformed);}}")
        if op["id"] == 3:
            out.append("crate::validate_offer(raw)?;")
        else:
            out.append(f"{op['body_layout']}::decode(raw)?;")
            for field in layouts[op["body_layout"]]["fields"]:
                n,off,size=field["name"],field["offset"],field["size"]
                if field["type"] not in scalars:
                    continue
                alias={"target_arch":"architecture","actor_kind":"config_actor_kind","file_kind":"config_file_kind","apply_class":"config_apply_class","state":"control_state"}
                key=alias.get(n,n)
                enum=contract["enums"].get(key)
                bits=contract["bitsets"].get(key)
                if enum:
                    values=pattern(set(enum.values())|{0})
                    out.append(f"if !matches!(crate::uint(&raw[{off}..{off+size}]), {values}) {{return Err(Error::InvalidEnum);}}")
                if bits:
                    mask=sum(1 << bit for bit in bits.values())
                    out.append(f"if crate::uint(&raw[{off}..{off+size}]) & !{mask}u64 != 0 {{return Err(Error::InvalidEnum);}}")
        out.append("Ok(()) },")
    out.append("_ => Err(Error::UnknownMessage) } }")
    write_rust("src/wire.rs","\n".join(out)+"\n")

if __name__ == "__main__":
    {"tests": tests, "wire": production}[sys.argv[1]]()
